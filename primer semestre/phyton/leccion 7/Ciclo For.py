# Ciclo "For", (en fundamentos de programación seria el ciclo Para, Hasta con paso a Hacer)
# La diferencia con el ciclo while es que el ciclo For, tiene un ciclo determinado de iteraciones,
# El ciclo while, tiene ciclo indeterminado.

cadena = 'Hello'
for letra in cadena:
    print(letra)
else:
    print('Fin del ciclo For')

