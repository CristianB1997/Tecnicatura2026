miVariable3 = 10
print(miVariable3)

#Operadores de reasignación
miVariable3 = miVariable3 + 1
print(miVariable3)
#De esta manera, se reduce la sintaxis de reasignación
#Se puede usar para todos los operadores aritméticos (+,-,/,*)
miVariable3 += 1
print(miVariable3)

miVariable3 -= 2
print(miVariable3)

miVariable3 *= 3
print(miVariable3)

miVariable3 /= 2
print(miVariable3)

miVariable1 = "ho"
miVariable2 = "la"
suma = miVariable1 + miVariable2
print(suma)

#Operadores de comparación

d = 4
b = 6
resultado = d == b # Comprobamos si son iguales
print(resultado)

# Operador diferente
resutado = d != b
print(resutado)

# Operador Mayor que
resutado = d > b
print(resutado)

# Operador menor que
resutado = d < b
print(resutado)

# Operador menor o igual que
resutado = d <= b
print(resutado)

# Operador mayor o igual que
resutado = d >= b
print(resutado)
