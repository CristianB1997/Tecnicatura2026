# Lista = Ariel, Liliana, Natalia, Osvaldo. En la lista se puede poner cualquier dato
# Cada dato, se le debe asignar un índice

nombres = ['Naty','Cristian','Ariel']
print(nombres)
# Asi se puede llamar de la lista, en este caso, los nombres de manera individual.
print(nombres[0])
print(nombres[1])
# Ahora para poder llamar los nombres de la lista de manera inversa.
# y no sabemos cuál es el último nombre de la lista usamos los números negativos:
print(nombres[-1])


